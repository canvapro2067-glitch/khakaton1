HISTORIC_STREETS = ("советская", "мостовая", "замковая")


def normalize(text: str) -> str:
    t = (text or "").lower().replace("ё", "е")
    t = t.replace("ул.", " ").replace("улица", " ").replace("пр-т", "проспект")
    t = t.replace("просп.", "проспект ").replace("г.гродно", " ").replace("гродно", " ")
    t = re.sub(r"[\"«»]", " ", t)
    t = re.sub(r"\s+", " ", t).strip()
    return t


def is_historic_address(address: str) -> bool:
    n = normalize(address)
    n = n.replace("сов.пограничников", "X").replace("сов пограничников", "X")
    n = n.replace("советских пограничников", "X")
    return any(re.search(rf"(^|[\s,]){s}([\s,]|$|\d)", n) for s in HISTORIC_STREETS)


GRODNO_LAT = (53.58, 53.78)
GRODNO_LON = (23.68, 23.96)


def in_grodno(lat: float, lon: float) -> bool:
    return GRODNO_LAT[0] <= lat <= GRODNO_LAT[1] and GRODNO_LON[0] <= lon <= GRODNO_LON[1]


def street_centroid(address: str) -> tuple[float, float] | None:
    n = normalize(address)
    for key in sorted(STREETS, key=len, reverse=True):
        if key in n:
            return STREETS[key]
    return None


def geocode_address(address: str) -> tuple[float, float, str]:
    n = normalize(address)
    best_key = ""
    for key in sorted(STREETS, key=len, reverse=True):
        if key in n:
            best_key = key
            break
    if not best_key:
        return GRODNO_CENTER[0], GRODNO_CENTER[1], "approx"
    lat, lon = STREETS[best_key]
    return lat, lon, f"street:{best_key}"


def haversine_m(a: tuple[float, float], b: tuple[float, float]) -> float:
    r = 6371000
    p1, p2 = math.radians(a[0]), math.radians(b[0])
    dp = math.radians(b[0] - a[0])
    dl = math.radians(b[1] - a[1])
    x = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * r * math.asin(min(1.0, math.sqrt(x)))


def road_distance_m(a: tuple[float, float], b: tuple[float, float]) -> int:
    # городской коэффициент вместо прямой: дворы, одностороннее, светофоры
    return int(haversine_m(a, b) * 1.38)


def travel_seconds(dist_m: int, hour: int) -> int:
    traffic = 1.15
    if 7 <= hour <= 9:
        traffic = 1.42
    elif 16 <= hour <= 19:
        traffic = 1.48
    elif 12 <= hour <= 14:
        traffic = 1.22
    speed_kmh = 27.0 / traffic
    return max(60, int(dist_m / (speed_kmh * 1000 / 3600)))


@dataclass
class Matrix:
    dist: list[list[int]]
    time: list[list[int]]


def build_matrix(points: list[tuple[float, float]], start_hour: int = 6) -> Matrix:
    n = len(points)
    dist = [[0] * n for _ in range(n)]
    time = [[0] * n for _ in range(n)]
    for i in range(n):
        for j in range(i + 1, n):
            d = road_distance_m(points[i], points[j])
            t = travel_seconds(d, start_hour)
            dist[i][j] = dist[j][i] = d
            time[i][j] = time[j][i] = t
    return Matrix(dist, time)
